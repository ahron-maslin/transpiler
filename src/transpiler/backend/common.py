import keyword


def escape_c_style(s: str) -> str:
    return (
        s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\t", "\\t")
        .replace("\r", "\\r")
    )


def escape_python_str(s: str) -> str:
    return escape_c_style(s)


def go_export_name(name: str) -> str:
    return name[0].upper() + name[1:] if name else name


def safe_ident(name: str, reserved: set) -> str:
    return f"{name}_" if name in reserved else name


